"""
Airflow DAG Compiler for TenantFlow.
Transpiles TenantConfig into deterministic Apache Airflow DAG definitions.
"""
from tenantflow.config.models import TenantConfig

DAG_TEMPLATE = """# Auto-generated by TenantFlow Dynamic DAG Factory
from datetime import datetime, timedelta
from airflow import DAG
from airflow.operators.bash import BashOperator

default_args = {{
    'owner': 'tenantflow',
    'depends_on_past': False,
    'email_on_failure': True,
    'retries': 2,
    'retry_delay': timedelta(minutes=3),
}}

with DAG(
    dag_id='tenantflow_{tenant_id}',
    default_args=default_args,
    description='Pipeline for {name} ({tier})',
    schedule_interval='{cron}',
    start_date=datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=['tenantflow', '{tier}'],
) as dag:

    validate_config = BashOperator(
        task_id='validate_tenant_config',
        bash_command='python3 -m tenantflow.cli validate --tenant-id {tenant_id}',
    )

    ingest_clinical = BashOperator(
        task_id='pyspark_clinical_ingest',
        bash_command='python3 -m tenantflow.cli run-spark --tenant-id {tenant_id} --job ingest',
    )

    aggregate_marts = BashOperator(
        task_id='pyspark_aggregate_marts',
        bash_command='python3 -m tenantflow.cli run-spark --tenant-id {tenant_id} --job aggregate',
    )

    validate_sla = BashOperator(
        task_id='verify_sla_target',
        bash_command='python3 -m tenantflow.cli verify-sla --tenant-id {tenant_id}',
    )

    validate_config >> ingest_clinical >> aggregate_marts >> validate_sla
"""

def compile_dag(tenant_cfg: TenantConfig) -> str:
    cron = "*/15 * * * *" if tenant_cfg.tier == "ENTERPRISE" else "0 * * * *"
    return DAG_TEMPLATE.format(
        tenant_id=tenant_cfg.tenant_id,
        name=tenant_cfg.name,
        tier=tenant_cfg.tier.value,
        cron=cron,
    )
